// TestCompareValue_ProtoMapEqualUnderReordering pins the proto.Equal-
// based map handling. Two Account protos with the same AssetV2 entries
// in different insertion orders MUST compare equal — otherwise Java's
// non-deterministic marshalling vs Go's deterministic marshalling
// would falsely fail the equivalence gate.
//
// Construction note: we hand-build two wire-format byte sequences with
// the AssetV2 entries in EXPLICITLY reversed order, instead of relying
// on Go's map iteration ordering. Map iteration is randomized at
// runtime but the randomization seed is stable within a process, so a
// `proto.Marshal` of two map literals with the same entries can
// accidentally produce identical bytes — which would make this test
// pass even if compareValue did byte-equality. The hand-built bytes
// guarantee the precondition we care about (goBytes != javaBytes) and
// the test asserts it explicitly.
func TestCompareValue_ProtoMapEqualUnderReordering(t *testing.T) {
	addr := bytes.Repeat([]byte{0x41}, 21)

	// Build the wire format by composing each side from two
	// single-entry Accounts. proto3 map fields are encoded as a
	// repeated entry; two consecutive entries can appear in either
	// order on the wire and decode to the same map.
	mk := func(id string, bal int64) []byte {
		raw, _ := proto.Marshal(&pb.Account{
			Address: addr,
			AssetV2: map[string]int64{id: bal},
		})
		return raw
	}
	entryA := mk("1000001", 100)
	entryB := mk("1000002", 200)

	// Strip the address from entryB's bytes and append to entryA;
	// the proto3 wire format allows duplicate field encoding (later
	// values append for map/repeated). The result decodes to a
	// 2-entry map but the on-wire order differs by argument order.
	goBytes := append([]byte{}, entryA...)
	goBytes = append(goBytes, entryB...)
	javaBytes := append([]byte{}, entryB...)
	javaBytes = append(javaBytes, entryA...)

	if bytes.Equal(goBytes, javaBytes) {
		t.Fatal("test precondition: hand-built byte sequences must differ; " +
			"the proto.Equal robustness is not actually being exercised")
	}

	equal, why := compareValue(stores.AccountStore, goBytes, javaBytes)
	if !equal {
		t.Errorf("proto.Equal-based diff failed under map reordering: %s", why)
	}
}

